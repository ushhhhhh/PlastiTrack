"""
Campus Sustainability Challenge: teams, participation and leaderboard.

Leaderboard rule (transparent and size-independent)
---------------------------------------------------
* A member has *comparable data* when they have at least two footprints
  produced by the current dataset version.
* For each such member: reduction % = (first weekly grams - latest weekly
  grams) / first weekly grams x 100.  (Members whose first record is 0 g
  cannot have a percentage and are excluded from the average only.)
* Team score = average reduction % across members with comparable data, so
  big teams do not win just by being big.
* Ranking: higher average reduction % first, then more members with
  comparable data, then team name.
* Teams with no comparable data are listed as "unranked", never ranked.
* Challenge completions (self-reported) are NOT used in the ranking.
* Teams created by the sample-data script are flagged ``is_sample: true``.
"""

from .. import models
from ..errors import ConflictError, NotFoundError, ValidationError
from . import footprint_service

LEADERBOARD_METHOD = (
    "Teams are ranked by the average measured reduction in weekly plastic "
    "(first vs. latest saved footprint) among members with at least two "
    "comparable footprints. Self-reported challenge completions are not "
    "counted. Teams without comparable data are unranked."
)
SAMPLE_TEAM_PREFIX = "[SAMPLE]"
SAMPLE_NOTE = ("Entries with is_sample = true were generated by the sample-"
               "data script for local testing. They are NOT real student "
               "participation.")


def _validate_team_name(name):
    if not isinstance(name, str) or not (2 <= len(name.strip()) <= 60):
        raise ValidationError("Invalid 'name'.",
                              {"name": "team name of 2-60 characters"})
    return name.strip()


def _validate_description(value):
    if value is None:
        return None
    if not isinstance(value, str) or len(value) > 300:
        raise ValidationError("Invalid 'description'.",
                              {"description": "text of at most 300 characters"})
    return value.strip() or None


def _team_to_dict(row):
    return {"id": row["id"], "name": row["name"],
            "description": row["description"],
            "is_sample": bool(row["is_sample"]),
            "created_at": row["created_at"]}


def create_team(db, name, description=None, is_sample=False):
    name = _validate_team_name(name)
    description = _validate_description(description)
    has_prefix = name.upper().startswith(SAMPLE_TEAM_PREFIX)
    if has_prefix and not is_sample:
        raise ValidationError(
            "Invalid 'name'.",
            {"name": "names starting with '%s' are reserved for sample data"
                     % SAMPLE_TEAM_PREFIX})
    if is_sample and not has_prefix:
        raise ValidationError("Sample team names must start with '%s'."
                              % SAMPLE_TEAM_PREFIX)
    # INSERT OR IGNORE + rowcount: duplicate names (even two requests at the
    # same instant) become a clean 409 instead of a UNIQUE-constraint crash.
    cur = db.execute(
        "INSERT OR IGNORE INTO teams (name, description, is_sample, "
        "created_at) VALUES (?, ?, ?, ?)",
        (name, description, 1 if is_sample else 0, models.now_iso()))
    db.commit()
    if cur.rowcount != 1:
        raise ConflictError("A team called '%s' already exists." % name)
    return get_team(db, cur.lastrowid)


def get_team(db, team_id):
    if isinstance(team_id, bool) or not isinstance(team_id, (int, str)) \
            or not str(team_id).isdigit():
        raise ValidationError("Invalid 'team_id'.",
                              {"team_id": "must be a positive whole number"})
    row = db.execute("SELECT * FROM teams WHERE id = ?",
                     (int(team_id),)).fetchone()
    if row is None:
        raise NotFoundError("Team %s not found." % team_id)
    team = _team_to_dict(row)
    team["member_count"] = db.execute(
        "SELECT COUNT(*) FROM team_members WHERE team_id = ?",
        (team["id"],)).fetchone()[0]
    return team


def list_teams(db):
    rows = db.execute(
        """SELECT t.*, COUNT(m.user_id) AS member_count
           FROM teams t LEFT JOIN team_members m ON m.team_id = t.id
           GROUP BY t.id ORDER BY t.name""").fetchall()
    teams = []
    for r in rows:
        team = _team_to_dict(r)
        team["member_count"] = r["member_count"]
        teams.append(team)
    return teams


def join_team(db, user_id, team_id, display_name=None, is_sample=False):
    """Register a participant in a team. Returns (membership, created)."""
    user_id = models.validate_user_id(user_id, sample=is_sample)
    display_name = models.validate_display_name(display_name)
    team = get_team(db, team_id)
    if team["is_sample"] != bool(is_sample):
        raise ConflictError(
            "Sample teams accept only sample users, and real teams accept "
            "only real users.")
    models.ensure_user(db, user_id, display_name, is_sample=is_sample)
    # Atomic: one team per user is enforced by the PRIMARY KEY; concurrent
    # duplicates insert nothing and fall through to the checks below.
    cur = db.execute(
        "INSERT OR IGNORE INTO team_members (user_id, team_id, joined_at) "
        "VALUES (?, ?, ?)", (user_id, team["id"], models.now_iso()))
    created = cur.rowcount == 1
    db.commit()
    membership = _membership(db, user_id)
    if not created and membership["team_id"] != team["id"]:
        raise ConflictError("User '%s' is already registered in another "
                            "team." % user_id)
    return membership, created


def _membership(db, user_id):
    row = db.execute(
        """SELECT m.user_id, m.joined_at, t.id AS team_id, t.name,
                  t.is_sample
           FROM team_members m JOIN teams t ON t.id = m.team_id
           WHERE m.user_id = ?""", (user_id,)).fetchone()
    if row is None:
        return None
    return {"user_id": row["user_id"], "team_id": row["team_id"],
            "team_name": row["name"], "team_is_sample": bool(row["is_sample"]),
            "joined_at": row["joined_at"]}


def get_membership(db, user_id):
    return _membership(db, user_id)


# ---------------------------------------------------------- statistics ----

def _member_stats(db, user_id):
    records = footprint_service.comparable_records(db, user_id)
    stats = {"user_id": user_id, "records": len(records),
             "latest_weekly_grams": None, "latest_eco_score": None,
             "has_comparable_data": len(records) >= 2,
             "reduction_weekly_grams": None, "reduction_percent": None}
    if records:
        stats["latest_weekly_grams"] = records[-1]["weekly_grams"]
        stats["latest_eco_score"] = records[-1]["eco_score"]
    if len(records) >= 2:
        first = records[0]["weekly_grams"]
        last = records[-1]["weekly_grams"]
        # Kept unrounded so team averages are exact; rounded on output.
        stats["reduction_weekly_grams"] = first - last
        if first > 0:
            stats["reduction_percent"] = (first - last) / first * 100
    return stats


def _avg(values):
    values = [v for v in values if v is not None]
    return round(sum(values) / len(values), 2) if values else None


def team_summary(db, team):
    members = [r["user_id"] for r in db.execute(
        "SELECT user_id FROM team_members WHERE team_id = ? ORDER BY user_id",
        (team["id"],))]
    stats = [_member_stats(db, uid) for uid in members]
    comparable = [s for s in stats if s["has_comparable_data"]]
    completed = db.execute(
        """SELECT COUNT(*) FROM user_challenges uc
           JOIN team_members m ON m.user_id = uc.user_id
           WHERE m.team_id = ? AND uc.status = 'completed'""",
        (team["id"],)).fetchone()[0]
    return {
        "team_id": team["id"], "team_name": team["name"],
        "is_sample": team["is_sample"],
        "member_count": len(members),
        "members_with_records": sum(1 for s in stats if s["records"]),
        "members_with_comparable_data": len(comparable),
        "total_footprint_records": sum(s["records"] for s in stats),
        "average_latest_weekly_grams": _avg(
            [s["latest_weekly_grams"] for s in stats]),
        "average_latest_eco_score": _avg(
            [s["latest_eco_score"] for s in stats]),
        "total_measured_weekly_reduction_grams": round(
            sum(s["reduction_weekly_grams"] for s in comparable), 4),
        "average_reduction_percent": _avg(
            [s["reduction_percent"] for s in comparable]),
        "self_reported_challenges_completed": completed,
    }


def _summaries(db, include_sample):
    teams = [t for t in list_teams(db) if include_sample or not t["is_sample"]]
    return [team_summary(db, t) for t in teams]


def campus_summary(db, include_sample=True):
    teams = _summaries(db, include_sample)
    return {
        "contains_sample_data": any(t["is_sample"] for t in teams),
        "sample_note": SAMPLE_NOTE,
        "totals": {
            "teams": len(teams),
            "participants": sum(t["member_count"] for t in teams),
            "participants_with_comparable_data": sum(
                t["members_with_comparable_data"] for t in teams),
            "footprint_records": sum(t["total_footprint_records"]
                                     for t in teams),
            "total_measured_weekly_reduction_grams": round(sum(
                t["total_measured_weekly_reduction_grams"] for t in teams), 4),
            "self_reported_challenges_completed": sum(
                t["self_reported_challenges_completed"] for t in teams),
        },
        "teams": teams,
    }


def leaderboard(db, include_sample=True):
    teams = _summaries(db, include_sample)
    ranked = [t for t in teams if t["average_reduction_percent"] is not None]
    unranked = [t for t in teams if t["average_reduction_percent"] is None]
    ranked.sort(key=lambda t: (-t["average_reduction_percent"],
                               -t["members_with_comparable_data"],
                               t["team_name"].lower()))
    entries = []
    previous_key, rank = None, 0
    for position, t in enumerate(ranked, start=1):
        key = (t["average_reduction_percent"],
               t["members_with_comparable_data"])
        if key != previous_key:  # equal scores share a rank
            rank, previous_key = position, key
        entries.append(dict(t, rank=rank))
    for t in unranked:
        t["unranked_reason"] = ("No member has two comparable footprints "
                                "with a non-zero baseline yet.")
    return {
        "method": LEADERBOARD_METHOD,
        "contains_sample_data": any(t["is_sample"] for t in teams),
        "sample_note": SAMPLE_NOTE,
        "leaderboard": entries,
        "unranked": unranked,
    }
